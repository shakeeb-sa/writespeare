/**
 * researchStore — the renderer's transient state for the research feature.
 *
 * Holds the state that drives the Sources and Documents tabs on
 * the topic-detail page:
 *
 *   candidatesByTopic      — per-topic bucket-keyed candidate lists.
 *                            Each topic's slot is a full
 *                            `CandidatesByBucket` record, one array
 *                            per time-range bucket.
 *   searchProgressByTopic  — per-topic per-bucket live search
 *                            progress; a bucket's slot is null when
 *                            not currently in flight.
 *   extractProgressByTopic — per-topic live extraction progress.
 *   extractedCountByTopic  — per-topic count of docs saved by the
 *                            last extraction.
 *   failedByTopic          — per-topic list of URLs whose extraction
 *                            failed, loaded from `failures.json`.
 *   statusByTopic          — per-topic lifecycle state.
 *   errorByTopic           — per-topic last error message, or null.
 *   activeTopicId          — the topic that most recently started a
 *                            search; tracking field only.
 *
 * And the actions the components call to drive those operations:
 *
 *   runFullSearch     — invoke the search IPC once per configured
 *                       bucket, sequentially; update per-bucket
 *                       progress as each bucket runs
 *   runExtraction     — invoke the extract IPC with the selected
 *                       URLs
 *   retryFailed       — re-run extraction for the URLs whose last
 *                       attempt failed
 *   cancelOperation   — cancel whatever is running for a topic
 *   loadCandidates    — read the topic's saved candidates and
 *                       failures from disk on first open
 *   clearCandidates   — empty one topic's candidate buckets
 *   clearError        — dismiss the last error for one topic
 *   reset             — return every field to its initial value
 *
 * ── How the store receives updates ────────────────────────────
 *
 *   The store does not poll. It does not hold an IPC listener per
 *   component. Instead, on module load, it installs ONE listener on
 *   the `research:marker` channel via the preload's generic
 *   `window.electronAPI.on(...)` API. Every marker the main
 *   process emits (from searchService, from extractionService, and
 *   later from the writer and validation services) flows through
 *   that one listener; the store's handler routes it to the state
 *   field the marker type maps to.
 *
 *   The one-listener design is deliberate. The alternative — each
 *   component that needs progress data attaches its own listener —
 *   would create as many listeners as there are mounted
 *   components, all receiving the same events, all updating local
 *   state, all of them going stale in slightly different ways.
 *   Centralising the subscription in the store means the state has
 *   exactly one writer per marker type, and components just read
 *   what they need from the store.
 *
 *   The listener is installed at module load. By the time a
 *   renderer's bundle imports this module (which happens when the
 *   app mounts the store for the first time), the preload has
 *   already run and `window.electronAPI` is available. The
 *   `typeof window !== 'undefined'` guard is defensive — it costs
 *   nothing and it keeps the module from throwing if it is ever
 *   imported in a non-renderer context (a future test harness that
 *   exercises the store's reducers directly).
 *
 * ── Why the store is NOT persisted ────────────────────────────
 *
 *   Unlike `userStore` (which persists the session token) and
 *   `settingsStore` (which caches user preferences), this store
 *   holds purely transient UI state. The candidate list is
 *   regenerated by a fresh search; the progress fields are only
 *   meaningful while an operation is in flight; the error is
 *   cleared on the next attempt. Persisting any of it would
 *   produce confusing resurrections after a restart — a candidate
 *   list from an old search appearing under a topic the user is
 *   visiting for the first time in days. The store therefore uses
 *   plain `create()` with no `persist` middleware.
 *
 *   The `candidatesByTopic` and `failedByTopic` records are
 *   repopulated on first open of each topic by the
 *   `loadCandidates` action, which reads the topic's on-disk
 *   `candidates.json` and `failures.json` via the main process.
 *
 * ── The per-topic, per-bucket design ──────────────────────────
 *
 *   Every piece of research state is a record keyed by the
 *   topic's ID, so switching between topics never clobbers the
 *   previous topic's data. The marker handler routes each
 *   incoming marker to its own topic's slot using the `topicId`
 *   on the payload — a marker that arrives while the user is
 *   viewing a different topic still updates the correct slot.
 *
 *   Within a topic, the candidate list is keyed by time-range
 *   bucket (`'anytime' | 'year' | 'month' | 'week'`) rather than
 *   being a single flat array. The four buckets correspond to the
 *   four time ranges the search pipeline queries, and each bucket
 *   carries its own candidate list and its own progress slot. A
 *   bucket that was configured with a zero count is skipped
 *   entirely — it never produces candidates and never shows
 *   progress.
 *
 *   Extraction is not bucketed: it processes a flat list of URLs
 *   the user selected, and its progress is a single per-topic
 *   value. A separate `failedByTopic` record tracks URLs whose
 *   extraction failed so that the retry flow can re-run just
 *   those.
 *
 * ── Why the type-only import from listenerBridge ──────────────
 *
 *   `MarkerEvent` is the shape of every marker the store receives.
 *   It is declared in `listenerBridge.ts` — the main-process
 *   module that parses the Python scripts' `::ROOKIE::` output.
 *   The store wants that type, but it CANNOT take a runtime import
 *   of the bridge module: `listenerBridge.ts` imports
 *   `BrowserWindow` from `electron`, and `BrowserWindow` is a
 *   main-process-only export. A runtime import would crash the
 *   renderer at bundle time.
 *
 *   The fix is the `import type` form — TypeScript erases it at
 *   emit time, so the compiled renderer bundle contains no
 *   reference to `listenerBridge`. The type is available to the
 *   compiler, unavailable to the runtime, and that is exactly what
 *   is wanted.
 *
 *   The channel name `'research:marker'` is declared as a local
 *   constant in this file rather than imported from the bridge.
 *   The two strings must match; they are documented in both files
 *   as a cross-module contract. A future session that adds a
 *   runtime-safe constants module (one that both processes can
 *   import) would replace the local constant with an import; that
 *   change is not in the current plan.
 *
 * What this store does NOT do:
 *
 *   - It does not persist. See above.
 *
 *   - It does not call the backend directly. The IPC handler
 *     (`researchIPC.ts`) is the one that reaches the backend when
 *     it needs to — for example, to persist an extraction's doc
 *     metadata. The store's IPC calls go through the preload's
 *     `window.electronAPI.research.*` methods, which are the same
 *     channels every other feature's calls use.
 *
 *   - It does not own the document list. Extracted `.md` files
 *     are the documents feature's concern; the `documentStore`
 *     holds them. This store only knows the COUNT of documents
 *     the last extraction produced (`extractedCount`), which is
 *     enough for the progress panel that shows "5 docs saved".
 *
 *   - It does not handle the captcha or manual-action modals.
 *     Those markers (`CAPTCHA_REQUIRED`, `CAPTCHA_SOLVED`,
 *     `MANUAL_ACTION`) reach the renderer over the same channel
 *     and are routed by the automation store (Session 20). This
 *     store's handler explicitly ignores those marker types.
 *
 *   - It does not distinguish a partial success from a failure.
 *     A search that collected ten candidates before hitting a
 *     rate-limit is a "success" from this store's perspective —
 *     the ten candidates are in the list, the user can act on
 *     them. A future session that wants richer classification
 *     would add fields to the state; the current shape matches
 *     what the UI needs.
 */

import { create } from 'zustand';

import type { MarkerEvent } from '../services/listenerBridge.js';

