/**
 * researchStore — the renderer's transient state for the research feature.
 *
 * Holds the state that drives the Sources and Documents tabs on
 * the topic-detail page:
 *
 *   candidates       — the search result list the user is reviewing
 *   searchProgress   — live progress during a search
 *   extractProgress  — live progress during extraction
 *   extractedCount   — how many doc files the last extraction saved
 *   error            — the last error from either operation
 *   activeTopicId    — which topic the state belongs to
 *
 * And the actions the components call to drive those operations:
 *
 *   startSearch       — invoke the search IPC and update state
 *                       as the operation runs
 *   runExtraction     — invoke the extract IPC with the selected
 *                       URLs
 *   cancelOperation   — cancel whatever is running for a topic
 *   clearCandidates   — empty the candidate list (after the user
 *                       moves on to extraction)
 *   clearError        — dismiss the last error
 *   reset             — return every field to its initial value
 *
 * ── How the store receives updates ────────────────────────────
 *
 *   The store does not poll. It does not hold an IPC listener per
 *   component. Instead, on module load, it installs ONE listener on
 *   the `research:marker` channel via the preload's generic
 *   `window.electronAPI.on(...)` API. Every marker the main
 *   process emits (from searchService, from extractionService, and
 *   later from the writer and validation services) flows through
 *   that one listener; the store's handler routes it to the state
 *   field the marker type maps to.
 *
 *   The one-listener design is deliberate. The alternative — each
 *   component that needs progress data attaches its own listener —
 *   would create as many listeners as there are mounted
 *   components, all receiving the same events, all updating local
 *   state, all of them going stale in slightly different ways.
 *   Centralising the subscription in the store means the state has
 *   exactly one writer per marker type, and components just read
 *   what they need from the store.
 *
 *   The listener is installed at module load. By the time a
 *   renderer's bundle imports this module (which happens when the
 *   app mounts the store for the first time), the preload has
 *   already run and `window.electronAPI` is available. The
 *   `typeof window !== 'undefined'` guard is defensive — it costs
 *   nothing and it keeps the module from throwing if it is ever
 *   imported in a non-renderer context (a future test harness that
 *   exercises the store's reducers directly).
 *
 * ── Why the store is NOT persisted ────────────────────────────
 *
 *   Unlike `userStore` (which persists the session token) and
 *   `settingsStore` (which caches user preferences), this store
 *   holds purely transient UI state. The candidate list is
 *   regenerated by a fresh search; the progress fields are only
 *   meaningful while an operation is in flight; the error is
 *   cleared on the next attempt. Persisting any of it would
 *   produce confusing resurrections after a restart — a candidate
 *   list from an old search appearing under a topic the user is
 *   visiting for the first time in days. The store therefore uses
 *   plain `create()` with no `persist` middleware.
 *
 * ── The single-topic design ───────────────────────────────────
 *
 *   The store holds ONE topic's research state at a time,
 *   identified by `activeTopicId`. The plan's user journey shows
 *   the user working on one topic's pipeline in the detail view;
 *   a second topic's search would replace the first's state in
 *   this store. The `activeTopicId` field is what lets the marker
 *   handler FILTER out markers that belong to a different topic —
 *   a search for topic B that starts while topic A's state is
 *   still in the store does not clobber A's candidate list,
 *   because the handler drops B's markers (their payload's
 *   `topicId` does not match `activeTopicId`).
 *
 *   The design assumption is: the user looks at one topic at a
 *   time. If a future session needs to run four topics' searches
 *   in parallel and show all four progress bars simultaneously,
 *   the store would change from flat state to a
 *   `Map<topicId, ResearchState>` and the marker handler would
 *   use the payload's `topicId` as a map key rather than as a
 *   filter. That refactor is a mechanical change confined to this
 *   file; the services and IPC handlers above it are unaffected.
 *
 * ── Why the type-only import from listenerBridge ──────────────
 *
 *   `MarkerEvent` is the shape of every marker the store receives.
 *   It is declared in `listenerBridge.ts` — the main-process
 *   module that parses the Python scripts' `::ROOKIE::` output.
 *   The store wants that type, but it CANNOT take a runtime import
 *   of the bridge module: `listenerBridge.ts` imports
 *   `BrowserWindow` from `electron`, and `BrowserWindow` is a
 *   main-process-only export. A runtime import would crash the
 *   renderer at bundle time.
 *
 *   The fix is the `import type` form — TypeScript erases it at
 *   emit time, so the compiled renderer bundle contains no
 *   reference to `listenerBridge`. The type is available to the
 *   compiler, unavailable to the runtime, and that is exactly what
 *   is wanted.
 *
 *   The channel name `'research:marker'` is declared as a local
 *   constant in this file rather than imported from the bridge.
 *   The two strings must match; they are documented in both files
 *   as a cross-module contract. A future session that adds a
 *   runtime-safe constants module (one that both processes can
 *   import) would replace the local constant with an import; that
 *   change is not in the current plan.
 *
 * What this store does NOT do:
 *
 *   - It does not persist. See above.
 *
 *   - It does not call the backend directly. The IPC handler
 *     (`researchIPC.ts`) is the one that reaches the backend when
 *     it needs to — for example, to persist an extraction's doc
 *     metadata. The store's IPC calls go through the preload's
 *     `window.electronAPI.research.*` methods, which are the same
 *     channels every other feature's calls use.
 *
 *   - It does not own the document list. Extracted `.md` files
 *     are the documents feature's concern; the `documentStore`
 *     holds them. This store only knows the COUNT of documents
 *     the last extraction produced (`extractedCount`), which is
 *     enough for the progress panel that shows "5 docs saved".
 *
 *   - It does not handle the captcha or manual-action modals.
 *     Those markers (`CAPTCHA_REQUIRED`, `CAPTCHA_SOLVED`,
 *     `MANUAL_ACTION`) reach the renderer over the same channel
 *     and are routed by the automation store (Session 20). This
 *     store's handler explicitly ignores those marker types.
 *
 *   - It does not distinguish a partial success from a failure.
 *     A search that collected ten candidates before hitting a
 *     rate-limit is a "success" from this store's perspective —
 *     the ten candidates are in the list, the user can act on
 *     them. A future session that wants richer classification
 *     would add fields to the state; the current shape matches
 *     what the UI needs.
 */

import { create } from 'zustand';

import type { MarkerEvent } from '../services/listenerBridge.js';

// =============================================================================
//  Channel name
// =============================================================================
//
//  The IPC channel the main process emits every marker on. This
//  string MUST match `listenerBridge.ts`'s exported
//  `MARKER_EVENT_CHANNEL` constant. Declared locally because the
//  bridge module cannot be imported at runtime — see the file
//  header.

const MARKER_CHANNEL = 'research:marker';

// =============================================================================
//  Public types
// =============================================================================

/**
 * One candidate source page as the renderer receives it.
 *
 * The shape is identical to the `SearchCandidate` interface
 * declared in `searchService.ts`, but it is re-declared here
 * rather than imported because the main-process service module
 * cannot be imported from the renderer — it depends on the
 * Electron main process's `app` and on Node's child-process
 * machinery, neither of which the renderer can access.
 *
 * The two declarations must stay in sync. A marker whose candidate
 * payload is missing a field will be silently narrowed by
 * `narrowCandidate` below (dropping the malformed candidate); if
 * the two sides drift on the field SET, that narrowing will drop
 * every candidate rather than crash, which is the correct failure
 * mode — the user sees an empty list and can retry.
 */
export interface SearchCandidate {
  /** The absolute URL of the page. */
  url: string;

  /** The page's title, as displayed on the SERP. */
  title: string;

  /** The SERP snippet — a short preview of the page's content.
   *  May be an empty string when the SERP did not carry one. */
  snippet: string;

  /** The platform slug for the URL's domain — `'reddit'`,
   *  `'quora'`, `'medium'`, `'twitter'`, or `'generic'`. */
  platform: string;
}

/**
 * The lifecycle state of the research feature's current
 * operation. Mirrors the pattern used by every other store in the
 * codebase (`TopicStoreStatus`, `UserStoreState.isLoading`).
 *
 *   'idle'       — no operation is running, and the last one (if
 *                  any) succeeded. The default state.
 *   'searching'  — a search is in flight.
 *   'extracting' — an extraction is in flight.
 *   'error'      — the last operation failed. `error` carries a
 *                  user-facing message.
 */
export type ResearchStoreStatus =
  | 'idle'
  | 'searching'
  | 'extracting'
  | 'error';

/**
 * Live search progress, as reported by the Python script's
 * `SEARCH_PROGRESS` marker.
 *
 *   page      — the 1-based index of the page currently being
 *               processed.
 *   found     — how many candidates have been collected so far.
 *   requested — the target number the caller asked for.
 *
 * The UI uses `found / requested` as a rough progress estimate —
 * not exact, because the search may stop early (fewer results
 * than requested) or overshoot (a page returns more than the
 * remaining count).
 */
export interface SearchProgress {
  page: number;
  found: number;
  requested: number;
}

/**
 * Live extraction progress, as reported by the Python script's
 * `EXTRACT_PROGRESS` marker.
 *
 *   index  — the 1-based index of the URL currently being
 *            extracted.
 *   total  — how many URLs the caller asked to extract.
 *   url    — the URL currently being processed.
 *   status — one of `'loading'`, `'saved'`, `'failed'`. The UI
 *            renders a per-URL badge from this value.
 */
export interface ExtractProgress {
  index: number;
  total: number;
  url: string;
  status: 'loading' | 'saved' | 'failed';
}

/**
 * The full shape of the research store's state, including the
 * data fields and the actions.
 */
export interface ResearchStoreState {
  // ---- Data ----

  /** The candidate list from the current topic's last search. */
  candidates: SearchCandidate[];

  /** The topic the state belongs to, or null when no topic is
   *  active. Every marker whose payload's `topicId` does not
   *  match this value is dropped by the marker handler. */
  activeTopicId: string | null;

  /** The current operation's lifecycle state. See
   *  `ResearchStoreStatus`. */
  status: ResearchStoreStatus;

  /** Live progress during a search, or null when no search is
   *  in flight (and the last one, if any, is not being reported). */
  searchProgress: SearchProgress | null;

  /** Live progress during extraction, or null when no extraction
   *  is in flight. */
  extractProgress: ExtractProgress | null;

  /** How many doc files the last extraction saved. Reset to 0 at
   *  the start of a new extraction. */
  extractedCount: number;

  /** The last error message, or null. Cleared at the start of
   *  every new operation and by `clearError`. */
  error: string | null;

  // ---- Actions ----

  /**
   * Run a search for a topic. Invokes `window.electronAPI.research.search`
   * and updates the state as the operation progresses.
   *
   * On success, the candidate list is populated both by this
   * action's return path AND by the `SEARCH_RESULT` marker that
   * arrives over the marker channel. The two are the same data;
   * whichever lands first wins, and the second is a no-op
   * (assigning an equivalent array is harmless).
   *
   * Returns `true` on success, `false` on failure. The caller
   * (typically `useResearch`) can use the boolean to decide
   * whether to surface a toast.
   */
  startSearch: (
    topicId: string,
    title: string,
    keywords?: string[]
  ) => Promise<boolean>;

  /**
   * Run an extraction on the given URLs. Invokes
   * `window.electronAPI.research.extract` and updates state as
   * the operation progresses.
   *
   * Returns the number of documents saved, or 0 on failure. The
   * caller can use the number to decide whether to navigate to the
   * Documents tab.
   */
  runExtraction: (
    topicId: string,
    urls: string[]
  ) => Promise<number>;

  /**
   * Cancel whatever research operation is running for a topic.
   * Invokes `window.electronAPI.research.cancel`, which hard-kills
   * the Python subprocess (see `researchIPC.ts` for the
   * graceful-vs-hard distinction).
   *
   * Resolves once the IPC call has returned. Does not wait for
   * the process to have fully exited — the main process's
   * `killed` handler will emit a terminal event that the store
   * uses to flip `status` back to idle.
   */
  cancelOperation: (topicId: string) => Promise<void>;

  /** Empty the candidate list. Called after the user has moved on
   *  to extraction. */
  clearCandidates: () => void;

  /** Clear the last error message. */
  clearError: () => void;

  /** Reset every field to its initial value. */
  reset: () => void;

  /**
   * Internal — route one marker event to the correct state
   * update. Called by the module-level listener installed at
   * import time; not intended for direct use by components.
   */
  _handleMarker: (event: MarkerEvent) => void;
}

// =============================================================================
//  Initial state
// =============================================================================

/**
 * The store's initial data fields. Extracted as a constant so
 * `reset` can spread it into a new state object without
 * duplicating the literals.
 *
 * `status` starts as `'idle'`, not `'searching'` — the store does
 * not know what the user is about to do, and a `'searching'` that
 * is immediately overwritten on the next render is a needless
 * intermediate state. The active flag flips only when an action
 * actually starts.
 */
const INITIAL_STATE = {
  candidates: [] as SearchCandidate[],
  activeTopicId: null as string | null,
  status: 'idle' as ResearchStoreStatus,
  searchProgress: null as SearchProgress | null,
  extractProgress: null as ExtractProgress | null,
  extractedCount: 0,
  error: null as string | null,
};

// =============================================================================
//  Marker payload narrowing
// =============================================================================
//
//  Every marker's payload arrives as `unknown` — the bridge does
//  not validate payload shapes, and neither does the store until
//  it needs to read a specific field. The narrowing helpers below
//  are the boundary where the opaque `unknown` becomes a typed
//  value the store can act on. A malformed payload is silently
//  ignored (the marker is dropped) rather than throwing — a
//  broken marker should not be able to crash the whole UI.

/**
 * Narrow a marker's payload to a shape that includes a `topicId`
 * field, or return null. Used by every marker handler to check
 * that the marker belongs to the store's currently-active topic.
 */
const readTopicId = (payload: unknown): string | null => {
  if (typeof payload !== 'object' || payload === null) {
    return null;
  }
  const t = (payload as { topicId?: unknown }).topicId;
  return typeof t === 'string' && t.length > 0 ? t : null;
};

/**
 * Narrow a `SEARCH_PROGRESS` payload into a `SearchProgress`. All
 * three numeric fields are required; a payload missing one is
 * dropped.
 */
const narrowSearchProgress = (payload: unknown): SearchProgress | null => {
  if (typeof payload !== 'object' || payload === null) return null;
  const p = payload as Record<string, unknown>;
  const page = p['page'];
  const found = p['found'];
  const requested = p['requested'];
  if (
    typeof page !== 'number' ||
    typeof found !== 'number' ||
    typeof requested !== 'number'
  ) {
    return null;
  }
  return { page, found, requested };
};

/**
 * Narrow a `SEARCH_RESULT` payload into a candidate array. Any
 * candidate entry missing `url` or `title` is dropped; the array
 * may therefore be shorter than the source, or empty.
 */
const narrowCandidates = (payload: unknown): SearchCandidate[] => {
  if (typeof payload !== 'object' || payload === null) return [];
  const raw = (payload as { candidates?: unknown }).candidates;
  if (!Array.isArray(raw)) return [];

  const result: SearchCandidate[] = [];
  for (const entry of raw) {
    if (typeof entry !== 'object' || entry === null) continue;
    const e = entry as Record<string, unknown>;
    const url = e['url'];
    const title = e['title'];
    if (typeof url !== 'string' || url.length === 0) continue;
    if (typeof title !== 'string' || title.length === 0) continue;
    const snippet = typeof e['snippet'] === 'string' ? e['snippet'] : '';
    const platform =
      typeof e['platform'] === 'string' ? e['platform'] : 'generic';
    result.push({ url, title, snippet, platform });
  }
  return result;
};

/**
 * Narrow an `EXTRACT_PROGRESS` payload into an `ExtractProgress`.
 * The `status` field is additionally constrained to the three
 * values the UI knows how to render; an unknown status is
 * normalized to `'loading'` (the safe default — it does not
 * claim a save that did not happen).
 */
const narrowExtractProgress = (
  payload: unknown
): ExtractProgress | null => {
  if (typeof payload !== 'object' || payload === null) return null;
  const p = payload as Record<string, unknown>;
  const index = p['index'];
  const total = p['total'];
  const url = p['url'];
  const statusRaw = p['status'];
  if (
    typeof index !== 'number' ||
    typeof total !== 'number' ||
    typeof url !== 'string' ||
    url.length === 0
  ) {
    return null;
  }
  const status: 'loading' | 'saved' | 'failed' =
    statusRaw === 'saved' || statusRaw === 'failed'
      ? statusRaw
      : 'loading';
  return { index, total, url, status };
};

/**
 * Narrow an `EXTRACT_DONE` payload into the number of docs saved.
 * Returns 0 for a malformed payload; a "0 saved" is a legitimate
 * value (an extraction that succeeded on the pipeline's side but
 * found nothing to save), so the fallback is not a lie.
 */
const narrowSavedCount = (payload: unknown): number => {
  if (typeof payload !== 'object' || payload === null) return 0;
  const n = (payload as { savedCount?: unknown }).savedCount;
  return typeof n === 'number' && n >= 0 ? n : 0;
};

