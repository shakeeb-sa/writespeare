//  Store
// =============================================================================

/**
 * The research store. See the file header for its responsibilities,
 * its subscription model, and the reasoning behind its
 * non-persistence.
 *
 * Created without middleware. The store is not persisted (see the
 * file header), does not use Immer (Zustand's built-in
 * `set(fn)` form is sufficient for the shallow updates this store
 * performs), and does not need `devtools` (the codebase does not
 * use the Redux DevTools bridge anywhere else).
 */
export const useResearchStore = create<ResearchStoreState>(
  (set, get) => ({
    // ---- Initial data ----
    ...INITIAL_STATE,

    // ---- Marker handler ----
    //
    // The store's single point of contact with the marker stream.
    // Every marker type is checked against the store's active
    // topic; a marker for a different topic is dropped. This is
    // what makes the store's single-topic model work under
    // parallel operations — see the file header.
    _handleMarker: (event: MarkerEvent): void => {
      const topicId = readTopicId(event.payload);
      if (topicId === null) return;
      if (topicId !== get().activeTopicId) return;

      switch (event.type) {
        case 'SEARCH_PROGRESS': {
          const progress = narrowSearchProgress(event.payload);
          if (progress !== null) {
            set({ searchProgress: progress });
          }
          return;
        }

        case 'SEARCH_RESULT': {
          const candidates = narrowCandidates(event.payload);
          set({
            candidates,
            // A terminal marker ends the operation's
            // in-flight state. If the search yielded zero
            // candidates the store still shows 'idle' — the
            // distinction between "empty result" and "still
            // running" is what the UI actually needs.
            status: 'idle',
            searchProgress: null,
          });
          return;
        }

        case 'EXTRACT_PROGRESS': {
          const progress = narrowExtractProgress(event.payload);
          if (progress !== null) {
            set({ extractProgress: progress });
          }
          return;
        }

        case 'EXTRACT_DONE': {
          const savedCount = narrowSavedCount(event.payload);
          set({
            extractedCount: savedCount,
            status: 'idle',
            extractProgress: null,
          });
          return;
        }

        case 'TASK_END': {
          // The main process's task-boundary marker. If the
          // task ended with a failure status, ensure the
          // store is not stuck in a transient state.
          const payload = event.payload as
            | { status?: unknown }
            | null
            | undefined;
          const status =
            payload && typeof payload.status === 'string'
              ? payload.status
              : '';
          if (status === 'failed' || status === 'aborted') {
            set({ status: 'idle' });
          }
          return;
        }

        default:
          // TASK_START, CAPTCHA_REQUIRED, CAPTCHA_SOLVED,
          // MANUAL_ACTION, WRITER_*, VALIDATION_* — none of
          // these are this store's concern. Each is handled
          // by the store that owns the corresponding stage
          // (automationStore, writerStore, validationStore).
          return;
      }
    },

    // ---- startSearch ----
    startSearch: async (
      topicId: string,
      title: string,
      keywords?: string[]
    ): Promise<boolean> => {
      // Clear any stale state from a previous search on a
      // different topic. The new topic is now the active one.
      set({
        activeTopicId: topicId,
        candidates: [],
        searchProgress: null,
        extractProgress: null,
        extractedCount: 0,
        error: null,
        status: 'searching',
      });

      try {
        const result = await window.electronAPI.research.search(
          topicId,
          title,
          keywords
        );

        if (result.success) {
          // The candidate list itself arrives over the
          // marker channel — this return path is a
          // summary. If the marker has already landed the
          // list is populated; if not, it will be on the
          // next event. Either way the operation is done.
          set({ status: 'idle', searchProgress: null });
          return true;
        }

        set({
          status: 'error',
          error: result.error ?? 'Search failed.',
          searchProgress: null,
        });
        return false;
      } catch (err) {
        // A rejected IPC promise is unusual — the preload
        // does not reject on business failures — but can
        // happen if the channel is unregistered (during a
        // window between app start and IPC registration)
        // or the renderer's context has been torn down.
        set({
          status: 'error',
          error:
            err instanceof Error
              ? err.message
              : 'Unable to reach the search service.',
          searchProgress: null,
        });
        return false;
      }
    },

    // ---- runExtraction ----
    runExtraction: async (
      topicId: string,
      urls: string[]
    ): Promise<number> => {
      set({
        activeTopicId: topicId,
        extractProgress: null,
        extractedCount: 0,
        error: null,
        status: 'extracting',
      });

      try {
        const result = await window.electronAPI.research.extract(
          topicId,
          urls
        );

        if (result.success && result.data) {
          const savedCount = result.data.savedCount;
          set({
            extractedCount: savedCount,
            status: 'idle',
            extractProgress: null,
          });
          return savedCount;
        }

        set({
          status: 'error',
          error: result.error ?? 'Extraction failed.',
          extractProgress: null,
        });
        return 0;
      } catch (err) {
        set({
          status: 'error',
          error:
            err instanceof Error
              ? err.message
              : 'Unable to reach the extraction service.',
          extractProgress: null,
        });
        return 0;
      }
    },

    // ---- cancelOperation ----
    cancelOperation: async (topicId: string): Promise<void> => {
      try {
        await window.electronAPI.research.cancel(topicId);
      } catch (err) {
        // Cancelling is a best-effort operation. A failure
        // here means the channel was unreachable, which is
        // itself the sign that whatever was running has
        // already stopped (the main process is gone). Log
        // for a developer; do not surface to the user.
        console.error(
          '[researchStore] cancelOperation failed:',
          err
        );
      }
      // The store's `status` is flipped by the marker handler
      // when the main process emits the `killed` /
      // `TASK_END` marker for this task. This function does
      // not optimistically set `status: 'idle'` — doing so
      // would race against a terminal marker that arrives a
      // moment later and briefly put the UI in a state the
      // operation never actually passed through.
    },

    // ---- Clear helpers ----
    clearCandidates: (): void => {
      set({ candidates: [], searchProgress: null });
    },

    clearError: (): void => {
      set({ error: null });
      if (get().status === 'error') {
        set({ status: 'idle' });
      }
    },

    reset: (): void => {
      set({ ...INITIAL_STATE });
    },
  })
);

// =============================================================================
//  Marker listener installation
// =============================================================================
//
//  The listener is installed ONCE at module load. See the file
//  header for why the subscription lives at the store level rather
//  than per-component.
//
//  The guard `typeof window !== 'undefined'` protects against a
//  non-renderer context (a future test harness that imports the
//  store to exercise its reducers). When the guard fails, the
//  store still works as a pure state container — actions write
//  state, components read state — but the marker stream never
//  arrives. In the app, the guard always passes.

if (
  typeof window !== 'undefined' &&
  typeof window.electronAPI === 'object' &&
  window.electronAPI !== null
) {
  window.electronAPI.on(MARKER_CHANNEL, (raw: unknown) => {
    // The preload passes the marker through unchanged. Its
    // runtime shape is `{ type: string, payload: unknown }`.
    // The type assertion here is safe because the channel is
    // owned by the main process's listenerBridge, which emits
    // exactly that shape for every message.
    useResearchStore
      .getState()
      ._handleMarker(raw as MarkerEvent);
  });
}

